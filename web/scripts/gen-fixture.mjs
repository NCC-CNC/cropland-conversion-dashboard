// Generates a SYNTHETIC fixture in the data contract shape
// (docs/design/02_mvp_data_contract.md) so the app can be developed without
// real pipeline output. The numbers are invented. Run: npm run fixture
import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'public', 'data');
const outDir = join(root, 'demo-fixture');
mkdirSync(outDir, { recursive: true });

const bbox = [-106.5, 52.2, -105.7, 52.7];
const cellM = 1000;
const midLat = (bbox[1] + bbox[3]) / 2;
const dLat = cellM / 111320;
const dLon = cellM / (111320 * Math.cos((midLat * Math.PI) / 180));
const classes = ['forest', 'grassland', 'wetland', 'shrubland'];
const snapshots = [2011, 2016, 2021, 2024];
const intervalDefs = [
  { from: 2011, to: 2024, years: 13 },
  { from: 2016, to: 2024, years: 8 },
  { from: 2021, to: 2024, years: 3 },
];

// Small deterministic PRNG (mulberry32).
let seed = 20240607;
function rnd() {
  seed |= 0;
  seed = (seed + 0x6d2b79f5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}
const r2 = (v) => Math.round(v * 100) / 100;

const lon = [];
const lat = [];
const areaHa = [];
const nat = { 2011: {}, 2016: {}, 2021: {} };
const conv = { 2011: {}, 2016: {}, 2021: {} };
for (const y of [2011, 2016, 2021]) for (const c of classes) { nat[y][c] = []; conv[y][c] = []; }

const nx = Math.floor((bbox[2] - bbox[0]) / dLon);
const ny = Math.floor((bbox[3] - bbox[1]) / dLat);
for (let iy = 0; iy < ny; iy++) {
  for (let ix = 0; ix < nx; ix++) {
    const fy = iy / ny;
    const fx = ix / nx;
    // Forest more common in the north, grassland in the south, wetlands in patches.
    const wet = Math.max(0, Math.sin(fx * 11) * Math.cos(fy * 9)) * 0.35;
    const base = {
      forest: Math.max(0, fy - 0.3 + (rnd() - 0.5) * 0.4) * 80,
      grassland: Math.max(0, 0.7 - fy + (rnd() - 0.5) * 0.4) * 70,
      wetland: wet * 100 * rnd(),
      shrubland: rnd() < 0.3 ? rnd() * 15 : 0,
    };
    const total = classes.reduce((s, c) => s + base[c], 0);
    if (total < 2) continue; // all crop or other: no natural cover, no entry
    const scale = total > 95 ? 95 / total : 1;
    // Conversion pressure: strongest in the south-west, absent for wetlands in some cells.
    const pressure = Math.max(0, 0.6 - fy * 0.6 - fx * 0.2 + (rnd() - 0.5) * 0.3);
    lon.push(Math.round((bbox[0] + (ix + 0.5) * dLon) * 1e5) / 1e5);
    lat.push(Math.round((bbox[1] + (iy + 0.5) * dLat) * 1e5) / 1e5);
    areaHa.push(100);
    for (const c of classes) {
      const remaining = base[c] * scale; // never converted by 2024
      const a = remaining * pressure * 0.15 * rnd(); // converted 2021 to 2024 (a)
      const b = remaining * pressure * 0.25 * rnd(); // 2016 to 2021
      const d = remaining * pressure * 0.3 * rnd(); // 2011 to 2016
      const n21 = remaining + a;
      const n16 = remaining + a + b;
      const n11 = remaining + a + b + d;
      nat[2021][c].push(r2(n21)); conv[2021][c].push(r2(a));
      nat[2016][c].push(r2(n16)); conv[2016][c].push(r2(a + b));
      nat[2011][c].push(r2(n11)); conv[2011][c].push(r2(a + b + d));
    }
  }
}

const cells = { lon, lat, area_ha: areaHa, intervals: {} };
for (const iv of intervalDefs) {
  cells.intervals[`${iv.from}-${iv.to}`] = { natural_ha: nat[iv.from], converted_ha: conv[iv.from] };
}

const meta = {
  area_id: 'demo-fixture',
  name: 'Demo fixture (SYNTHETIC data)',
  bbox,
  cell_size_m: cellM,
  snapshots,
  latest: 2024,
  natural_classes: classes,
  intervals: intervalDefs,
  method:
    'SYNTHETIC fixture generated by web/scripts/gen-fixture.mjs. Values are invented ' +
    'to exercise the interface and do not describe real land cover.',
  source: 'None. Synthetic data for interface development only.',
  generated: new Date().toISOString().slice(0, 10),
  caveats: [
    'This is SYNTHETIC demonstration data. Do not use these numbers for any decision.',
    'Real results come from the AAFC Annual Crop Inventory once the pipeline output is installed.',
  ],
};

writeFileSync(join(outDir, 'meta.json'), JSON.stringify(meta, null, 2) + '\n');
writeFileSync(join(outDir, 'cells.json'), JSON.stringify(cells));

// Add or refresh only the fixture entry in areas.json; keep other entries.
const areasPath = join(root, 'areas.json');
let areas = [];
if (existsSync(areasPath)) areas = JSON.parse(readFileSync(areasPath, 'utf8'));
areas = areas.filter((a) => a.id !== 'demo-fixture');
areas.push({ id: 'demo-fixture', name: meta.name, bbox });
writeFileSync(areasPath, JSON.stringify(areas, null, 2) + '\n');
console.log(`fixture: ${lon.length} cells`);
